import { createCanvas, Path2D } from "@napi-rs/canvas";
import { mkdir, writeFile } from "node:fs/promises";
await mkdir("build", { recursive: true });
const canvas = createCanvas(1024, 1024),
  c = canvas.getContext("2d");
c.scale(4, 4);
c.fillStyle = "#18212C";
c.beginPath();
c.roundRect(8, 8, 240, 240, 52);
c.fill();
c.strokeStyle = "#35495C";
c.lineWidth = 2;
c.stroke();
c.strokeStyle = "#83CEFF";
c.lineWidth = 17;
c.lineJoin = "round";
c.lineCap = "round";
c.stroke(new Path2D("M59 189L128 55L198 189M88 139H167M128 175V211"));
await writeFile("build/icon.png", canvas.toBuffer("image/png"));
const small = createCanvas(256, 256);
small.getContext("2d").drawImage(canvas, 0, 0, 256, 256);
const png = small.toBuffer("image/png");
const header = Buffer.alloc(22);
header.writeUInt16LE(1, 2);
header.writeUInt16LE(1, 4);
header.writeUInt16LE(1, 10);
header.writeUInt16LE(32, 12);
header.writeUInt32LE(png.length, 14);
header.writeUInt32LE(22, 18);
await writeFile("build/icon.ico", Buffer.concat([header, png]));
